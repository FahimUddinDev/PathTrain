async function seedTopics() {
  console.log("Finding Class 10 -> Caru o Karukola -> Shilpo Kola...");

  const cls = await prisma.class.findFirst({ where: { name: "Class 10" } });
  if (!cls) throw new Error("Class 10 not found");

  const subject = await prisma.subject.findFirst({
    where: { classId: cls.id, name: { contains: "Caru" } },
  });
  if (!subject) throw new Error("Subject Caru o Karukola not found");

  const chapter = await prisma.chapter.findFirst({
    where: { subjectId: subject.id, name: { contains: "Shilpo" } },
  });
  if (!chapter) throw new Error("Chapter Shilpo Kola not found");

  console.log(`Found Chapter: ${chapter.name} (${chapter.id})`);

  for (const item of topicsData) {
    let topic = await prisma.topic.findFirst({
      where: { chapterId: chapter.id, name: item.name },
    });

    if (!topic) {
      console.log(`Creating & Chunking topic: "${item.name}"...`);
      topic = await createAndChunkTopic({
        chapterId: chapter.id,
        name: item.name,
        text: item.text,
      });
    } else {
      console.log(`Topic "${item.name}" already exists (${topic.id})`);
    }

    if (topic.status !== "embedded") {
      console.log(`Embedding topic "${item.name}" chunks into pgvector...`);
      const result = await embedTopicChunks(topic.id);
      console.log(`Embedded ${result.embedded} chunks for topic "${item.name}".`);
    } else {
      console.log(`Topic "${item.name}" is already embedded.`);
    }
  }

  console.log("All topics created, chunked, and embedded successfully!");
}

